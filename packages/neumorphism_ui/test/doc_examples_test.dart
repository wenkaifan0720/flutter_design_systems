// neumorphicFontFamily: compiled, not run (it loads a font file).
Future<void> _compiled0(BuildContext context) async {
  final bytes = rootBundle.load('assets/fonts/Manrope-400.ttf');
  final loader = FontLoader(neumorphicFontFamily('Manrope'))..addFont(bytes);
  await loader.load();
  _keep(loader);
}

